export type TranslationKey = keyof typeof en;

export function translate(lang: Lang, key: TranslationKey, vars?: I18nVars): string {
  const dict = lang === 'hi' ? hi : en;
  let str = dict[key] ?? en[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(`{${k}}`, String(v));
    }
  }
  return str;
}

export function riskLevelLabel(lang: Lang, level: RiskLevel | string): string {
  const key = `risk.${level}` as TranslationKey;
  return lang === 'hi' && hi[key] ? hi[key] : (en[key] ?? level);
}

export function severityLabel(lang: Lang, severity: string): string {
  if (severity === 'RESOLVED') {
    return lang === 'hi' ? hi['severity.RESOLVED'] : en['severity.RESOLVED'];
  }
  return riskLevelLabel(lang, severity);
}

export function roleLabel(lang: Lang, role: string, full = false): string {
  const key = (full ? `role.full.${role}` : `role.${role}`) as TranslationKey;
  const dict = lang === 'hi' ? hi : en;
  return dict[key] ?? en[key] ?? role;
}

const dictionaries: Record<Lang, Record<TranslationKey, string>> = { en, hi };

const LANG_KEY = 'sankalp-lang';

interface I18nValue {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: TranslationKey, vars?: I18nVars) => string;
  riskLabel: (level: RiskLevel | string) => string;
  sevLabel: (severity: string) => string;
  roleLabel: (role: string, full?: boolean) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    if (typeof window === 'undefined') return 'en';
    return window.localStorage.getItem(LANG_KEY) === 'hi' ? 'hi' : 'en';
  });

  useEffect(() => {
    window.localStorage.setItem(LANG_KEY, lang);
    document.documentElement.lang = lang;
  }, [lang]);

  const t = (key: TranslationKey, vars?: I18nVars) => translate(lang, key, vars);
  const riskLabel = (level: RiskLevel | string) => riskLevelLabel(lang, level);
  const sevLabel = (severity: string) => severityLabel(lang, severity);
  const roleLbl = (role: string, full = false) => roleLabel(lang, role, full);

  return (
    <I18nContext.Provider value={{ lang, setLang, t, riskLabel, sevLabel, roleLabel: roleLbl }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within an I18nProvider');
  return ctx;
}